#!/usr/bin/env python3
"""Emit the runtime policy module consumed by the RPC capability filter.

The filter must not parse `policy.json` at run time: it runs in the workbench
renderer, on the hot path of every RPC call, before any file service is
available. So the table is compiled to a TypeScript module that the patch queue
adds to the tree.

Keeping this generated, rather than hand-written in the patch, is the whole
maintainability argument: an upstream bump edits `policy.json` and regenerates,
instead of rebasing a large diff.

Only what the filter needs is emitted -- verdicts, argument constraints and the
policy reference used in the denial log. Rationale, evidence and impact stay in
`policy.json` for humans and for the drift check.

Usage:
    python3 emit_policy.py [--out <path>] [--check]
"""

from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
POLICY = os.path.join(REPO, "rpc-filter", "policy", "policy.json")
COVERAGE = os.path.join(REPO, "rpc-filter", "policy", "coverage.json")
DEFAULT_OUT = os.path.join(REPO, "rpc-filter", "patch-src", "seclabPolicyData.ts")

HEADER = """/*---------------------------------------------------------------------------------------------
 *  seclab-vscode: generated RPC capability policy. DO NOT EDIT.
 *
 *  Generated by rpc-filter/tools/emit_policy.py from rpc-filter/policy/policy.json
 *  at upstream %s.
 *
 *  Regenerate with `rpc-filter/tools/emit.sh`; the drift check fails when this
 *  file disagrees with the policy table.
 *--------------------------------------------------------------------------------------------*/

export type SeclabVerdict = 'allow' | 'allow_with_constraint' | 'prompt' | 'rewrite' | 'deny';

export interface SeclabEntry {
	readonly verdict: SeclabVerdict;
	/** Stable key used in the denial log and by the probe checker. */
	readonly ref: string;
	/** Named argument constraint, applied by the filter's validators. */
	readonly constraint?: string;
}

"""


def _load(path):
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def build(policy: dict) -> dict:
    """The compact (key -> entry) form the filter indexes at run time."""
    rpc = {}
    for sid, service in policy.get("rpc", {}).items():
        for method, entry in (service.get("methods") or {}).items():
            rpc["%s.%s" % (sid, method)] = {
                "verdict": entry["verdict"],
                "ref": "rpc:%s.%s" % (sid, method),
                "constraint": entry.get("constraint"),
            }
    service_defaults = {
        sid: service.get("service_default", policy["default_verdict"])
        for sid, service in policy.get("rpc", {}).items()
    }
    commands = {}
    for cid, entry in (policy.get("commands", {}).get("exact") or {}).items():
        commands[cid] = {
            "verdict": entry["verdict"],
            "ref": "cmd:%s" % cid,
            "constraint": entry.get("constraint"),
        }
    channels = {}
    for name, entry in (policy.get("channels") or {}).items():
        if name in ("note", "server_initiated") or not isinstance(entry, dict):
            continue
        channels[name] = {
            "verdict": entry["verdict"],
            "ref": "chan:%s" % name,
            "constraint": entry.get("constraint"),
        }
    return {
        "default": policy["default_verdict"],
        "serviceDefaults": service_defaults,
        "rpc": rpc,
        "commands": commands,
        "channels": channels,
    }


def render(policy: dict, sha: str) -> str:
    data = build(policy)
    out = [HEADER % sha[:12]]

    def emit(name: str, mapping: dict, comment: str) -> None:
        out.append("/** %s */\n" % comment)
        out.append("export const %s: ReadonlyMap<string, SeclabEntry> = new Map([\n" % name)
        for key in sorted(mapping):
            e = mapping[key]
            fields = "verdict: '%s', ref: '%s'" % (e["verdict"], e["ref"])
            if e.get("constraint"):
                fields += ", constraint: '%s'" % e["constraint"].replace("'", "\\'")
            out.append("\t['%s', { %s }],\n" % (key, fields))
        out.append("]);\n\n")

    out.append("/** Verdict for anything not named below. Default-deny is the point. */\n")
    out.append("export const SECLAB_DEFAULT_VERDICT: SeclabVerdict = '%s';\n\n" % data["default"])
    emit("SECLAB_RPC", data["rpc"],
         "Keyed `<wire sid>.<method>`. The sid is the string passed to "
         "createProxyIdentifier, never the MainContext property name.")
    out.append("/** Per-service fallback for a method with no entry of its own. */\n")
    out.append("export const SECLAB_SERVICE_DEFAULTS: ReadonlyMap<string, SeclabVerdict> = new Map([\n")
    for sid in sorted(data["serviceDefaults"]):
        out.append("\t['%s', '%s'],\n" % (sid, data["serviceDefaults"][sid]))
    out.append("]);\n\n")
    emit("SECLAB_COMMANDS", data["commands"],
         "Commands reachable through $executeCommand. Only ids listed here are "
         "reachable; categories may withhold authority but never grant it.")
    emit("SECLAB_CHANNELS", data["channels"],
         "Channels the client serves to the server over the remote connection.")
    return "".join(out)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true",
                        help="fail if the emitted module differs from the file on disk")
    args = parser.parse_args(argv)

    policy = _load(POLICY)
    text = render(policy, policy["upstream_sha"])

    if args.check:
        try:
            with open(args.out, "r", encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            print("FAIL %s is missing; run rpc-filter/tools/emit.sh"
                  % os.path.relpath(args.out, REPO), file=sys.stderr)
            return 1
        if current != text:
            print("FAIL %s is stale; run rpc-filter/tools/emit.sh"
                  % os.path.relpath(args.out, REPO), file=sys.stderr)
            return 1
        print("policy module is in sync with the policy table")
        return 0

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    data = build(policy)
    print("wrote %s: %d rpc methods, %d commands, %d channels, default %s"
          % (os.path.relpath(args.out, REPO), len(data["rpc"]),
             len(data["commands"]), len(data["channels"]), data["default"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
