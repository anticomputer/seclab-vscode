// OCI tab sensor: Falco modern_ebpf on the Docker host kernel, outside every tab container
// (ADR tab-observability §2; user: "run it only while container tabs are open, filter events to
// tab containers at the source, and keep output local").
//   - one privileged Falco container per supervisor, started with the first OCI tab and removed
//     with the last; --network none, no docker.sock, stdout is the only output
//   - a capture-only ruleset, regenerated with the exact tab container ids and hot-reloaded
//     (SIGHUP), so other containers' events never leave Falco
//   - metrics snapshots every 2 s are the heartbeat; kernel drops mark tabs degraded
// Falco's output is tab-influenced (argv, paths): bounded, parsed strictly, normalised by the hub.

import type { ChildProcessWithoutNullStreams } from 'node:child_process';
import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';
import type { RunResult } from '../run.ts';
import type { ObsHub } from './hub.ts';
import { LineSplitter } from './sbx-collector.ts';
import { summarizeArgv } from './strace.ts';

export const FALCO_IMAGE = 'falcosecurity/falco:0.45.2@sha256:1562a643953f938e02f47319b5214d93a235f11f646d60e9b8a516fd5a64698e';
const SOURCE = { source: 'falco', integrity: 'host-observed' } as const;
const CID_RE = /^[0-9a-f]{64}$/;
const SHORT_RE = /^[0-9a-f]{12}$/;
// Paths reported even outside deep mode (credential-like; matches detect.ts CRED_PATH roots).
const CRED_PATH_PARTS = ['/.ssh/', '/.aws/', '/.git-credentials', '/.config/gh/', '/.docker/config.json', '/.kube/config', '/.gnupg/', '/.config/solana/', '/.electrum/', '/.config/Exodus/', '/.local/share/keyrings/', '/.mozilla/firefox/', '/.config/google-chrome/', '/.config/chromium/', '/.config/BraveSoftware/', '/.netrc', '/.npmrc', '/.pypirc'];

/** The capture-only ruleset for an exact set of tab containers. Never contains tab input. */
export function falcoRules(tabs: ReadonlyArray<{ shortId: string; deep: boolean }>): string {
	for (const t of tabs) {
		if (!SHORT_RE.test(t.shortId)) {
			throw new Error('invalid container id');
		}
	}
	const list = (ids: string[]) => (ids.length ? ids.map(i => `"${i}"`).join(', ') : '"000000000000"');
	const ids = list(tabs.map(t => t.shortId));
	const deep = list(tabs.filter(t => t.deep).map(t => t.shortId));
	const cred = CRED_PATH_PARTS.map(p => `fd.name contains "${p}"`).join(' or ');
	return `# Generated by seclab-tabd (tabd/src/obs/falco.ts); capture-only, tab containers only.
- macro: seclab_tab
  condition: container.id in (${ids}) and proc.exepath exists and not proc.exepath in ("/runc", "/usr/bin/runc", "/usr/sbin/runc", "/usr/local/bin/runc", "/usr/local/sbin/runc")
- macro: seclab_deep
  condition: container.id in (${deep})
- rule: seclab.exec
  desc: exec in a tab
  condition: evt.type in (execve, execveat) and evt.res=SUCCESS and seclab_tab
  output: exec %proc.pid %proc.ppid %user.uid %proc.exepath %proc.name %proc.args %proc.pcmdline %proc.apid[2] %proc.aname[2] %proc.apid[3] %proc.aname[3] %container.id
  priority: INFORMATIONAL
- rule: seclab.connect
  desc: connect from a tab
  condition: evt.type=connect and fd.typechar in (4, 6, u) and seclab_tab
  output: connect %proc.pid %proc.ppid %proc.exepath %proc.pcmdline %fd.typechar %fd.l4proto %fd.cport %evt.args %container.id
  priority: INFORMATIONAL
- rule: seclab.open
  desc: credential-like path opened in a tab (all opens in deep tabs)
  condition: evt.type in (open, openat, openat2) and seclab_tab and (seclab_deep or ${cred})
  output: open %proc.pid %proc.ppid %proc.exepath %proc.pcmdline %fd.name %evt.arg.flags %evt.res %container.id
  priority: INFORMATIONAL
- rule: seclab.fileop
  desc: unlink, rename, link, chmod in a tab
  condition: evt.type in (unlink, unlinkat, rename, renameat, renameat2, link, linkat, symlink, symlinkat, chmod, fchmodat) and evt.res=SUCCESS and seclab_tab
  output: fileop %proc.pid %proc.ppid %proc.exepath %proc.pcmdline %evt.type %fs.path.name %fs.path.source %fs.path.target %evt.args %container.id
  priority: INFORMATIONAL
- rule: seclab.priv
  desc: privilege, ptrace, signal and namespace calls in a tab
  condition: evt.type in (setuid, setgid, setresuid, setresgid, setreuid, setregid, capset, ptrace, kill, tkill, tgkill, mount, umount, umount2, unshare, setns, bpf, memfd_create, init_module, finit_module, pivot_root, chroot) and seclab_tab
  output: priv %proc.pid %proc.ppid %proc.exepath %proc.pcmdline %evt.type %evt.args %container.id
  priority: INFORMATIONAL
`;
}

export function falcoArgs(name: string, rulesDir: string, labels: Record<string, string>): string[] {
	if (!/^seclab-falco-[0-9a-f]{8}-[0-9]{1,10}$/.test(name) || !path.isAbsolute(rulesDir) || /[,:]/.test(rulesDir)) {
		throw new Error('invalid falco name or rules dir');
	}
	const args = ['run', '-i', '--rm', '--name', name, '--privileged', '--network', 'none', '--pids-limit', '512', '--memory', '1g'];
	for (const [k, v] of Object.entries(labels)) {
		args.push('--label', `${k}=${v}`);
	}
	args.push('--mount', 'type=bind,src=/proc,dst=/host/proc,readonly', '--mount', 'type=bind,src=/sys/kernel,dst=/sys/kernel,readonly',
		'--mount', `type=bind,src=${rulesDir},dst=/etc/seclab,readonly`, '--', FALCO_IMAGE,
		'falco', '-r', '/etc/seclab/rules.yaml');
	const o: Record<string, string> = {
		'engine.kind': 'modern_ebpf', 'json_output': 'true', 'json_include_output_property': 'false', 'json_include_tags_property': 'false',
		'stdout_output.enabled': 'true', 'file_output.enabled': 'false', 'http_output.enabled': 'false', 'program_output.enabled': 'false',
		'syslog_output.enabled': 'false', 'grpc_output.enabled': 'false', 'grpc.enabled': 'false', 'webserver.enabled': 'false',
		'metrics.enabled': 'true', 'metrics.interval': '2s', 'metrics.output_rule': 'true', 'metrics.rules_counters_enabled': 'false',
		'metrics.resource_utilization_enabled': 'false', 'metrics.state_counters_enabled': 'false', 'metrics.kernel_event_counters_enabled': 'true',
		'metrics.libbpf_stats_enabled': 'false', 'metrics.include_empty_values': 'false',
	};
	for (const [k, v] of Object.entries(o)) {
		args.push('-o', `${k}=${v}`);
	}
	return args;
}

export interface FalcoDeps {
	readonly hub: ObsHub;
	readonly rulesDir: string;
	readonly name: string;
	readonly labels: Record<string, string>;
	readonly spawnDocker: (args: string[]) => ChildProcessWithoutNullStreams;
	readonly runDocker: (args: string[]) => Promise<RunResult>;
	readonly pidAlive: (pid: number) => boolean;
	readonly readyTimeoutMs?: number;
}

interface Watched { tabId: string; deep: boolean }

export class FalcoSensor {
	private readonly d: FalcoDeps;
	private readonly tabs = new Map<string, Watched>(); // short container id -> tab
	private child?: ChildProcessWithoutNullStreams;
	private readyWaiters: Array<() => void> = [];
	private chain: Promise<void> = Promise.resolve();
	private cleaned = false;
	private wantSha = '';
	private errTail = '';

	constructor(d: FalcoDeps) {
		this.d = d;
	}

	/** Watch a tab container; resolves once Falco runs with a ruleset that includes it. */
	add(tabId: string, containerId: string, deep: boolean): Promise<void> {
		if (!CID_RE.test(containerId)) {
			return Promise.reject(new Error('invalid container id'));
		}
		const run = this.chain.then(async () => {
			const short = containerId.slice(0, 12);
			for (const [k, v] of this.tabs) {
				if (v.tabId === tabId && k !== short) {
					this.tabs.delete(k);
				}
			}
			const had = this.tabs.get(short);
			if (had && had.deep === deep && this.child) {
				return; // already watched by a running Falco
			}
			this.tabs.set(short, { tabId, deep });
			await this.apply();
			this.d.hub.heartbeat(tabId);
			this.d.hub.setObservation(tabId, 'observed', 'Falco watching the tab container', { sensor: 'falco', mode: deep ? 'deep' : 'default' });
		});
		this.chain = run.catch(() => undefined);
		return run;
	}

	/** Stop watching; the last tab out removes the Falco container. */
	remove(tabId: string): Promise<void> {
		const run = this.chain.then(async () => {
			for (const [k, v] of this.tabs) {
				if (v.tabId === tabId) {
					this.tabs.delete(k);
					this.d.hub.expectEnd(tabId);
					this.d.hub.sensorEnded(tabId, 'tab stopped', false);
				}
			}
			if (this.tabs.size === 0) {
				await this.stop();
			}
		});
		this.chain = run.catch(() => undefined);
		return run;
	}

	async stop(): Promise<void> {
		const c = this.child;
		this.child = undefined;
		if (c) {
			await this.d.runDocker(['rm', '-f', '--', this.d.name]);
			c.kill('SIGKILL');
		}
	}

	private async apply(): Promise<void> {
		if (!this.child && !this.cleaned) {
			await this.cleanupStale();
			this.cleaned = true;
		}
		fs.mkdirSync(this.d.rulesDir, { recursive: true, mode: 0o755 });
		const rules = falcoRules([...this.tabs].map(([shortId, w]) => ({ shortId, deep: w.deep })));
		this.wantSha = createHash('sha256').update(rules).digest('hex');
		const tmp = path.join(this.d.rulesDir, 'rules.yaml.tmp');
		fs.writeFileSync(tmp, rules, { mode: 0o644 });
		// Rewrite in place (not rename): a directory bind mount sees the new content either way.
		fs.copyFileSync(tmp, path.join(this.d.rulesDir, 'rules.yaml'));
		fs.rmSync(tmp, { force: true });
		const ready = this.waitReady();
		if (!this.child) {
			this.start();
		} else {
			const r = await this.d.runDocker(['kill', '--signal', 'HUP', '--', this.d.name]);
			if (r.code !== 0) {
				throw new Error(`could not reload Falco: ${r.stderr.trim().slice(-200)}`);
			}
		}
		await ready;
	}

	/** Remove Falco containers left by crashed supervisors of the same state dir. */
	private async cleanupStale(): Promise<void> {
		const state = this.d.labels['seclab.state'];
		const r = await this.d.runDocker(['ps', '-a', '--filter', 'label=seclab.obs=falco', '--filter', `label=seclab.state=${state}`, '--format', '{{.Names}}']);
		for (const name of r.stdout.split('\n').map(x => x.trim())) {
			const m = /^seclab-falco-[0-9a-f]{8}-([0-9]{1,10})$/.exec(name);
			if (m && name !== this.d.name && !this.d.pidAlive(Number(m[1]))) {
				await this.d.runDocker(['rm', '-f', '--', name]);
			}
		}
	}

	private waitReady(): Promise<void> {
		return new Promise((resolve, reject) => {
			const t = setTimeout(() => {
				this.readyWaiters = this.readyWaiters.filter(w => w !== done);
				reject(new Error(`Falco did not start capturing with the tab ruleset (does the Docker kernel support modern eBPF with BTF?): ${this.errTail.trim().split('\n').slice(-2).join(' | ').slice(0, 300)}`));
			}, this.d.readyTimeoutMs ?? 60_000);
			t.unref?.();
			const done = () => {
				clearTimeout(t);
				resolve();
			};
			this.readyWaiters.push(done);
		});
	}

	private start(): void {
		const child = this.d.spawnDocker(falcoArgs(this.d.name, this.d.rulesDir, this.d.labels));
		this.child = child;
		const out = new LineSplitter(64 * 1024);
		child.stdout.on('data', (b: Buffer) => out.push(b, l => this.line(l), () => undefined));
		child.stderr.on('data', (b: Buffer) => {
			this.errTail = (this.errTail + b.toString('utf8')).slice(-2048);
		});
		child.on('close', code => {
			if (this.child !== child) {
				return;
			}
			this.child = undefined;
			for (const w of this.tabs.values()) {
				this.d.hub.sensorEnded(w.tabId, `Falco exited (${code})`, true);
			}
		});
		child.on('error', () => undefined);
	}

	private line(buf: Buffer): void {
		if (buf[0] !== 0x7b) {
			return; // Falco's plain-text shutdown summary
		}
		let e: { rule?: unknown; time?: unknown; output_fields?: Record<string, unknown> };
		try {
			e = JSON.parse(buf.toString('utf8'));
		} catch {
			return;
		}
		const f = e.output_fields ?? {};
		if (e.rule === 'Falco internal: metrics snapshot') {
			// Ready = Falco is capturing with exactly the ruleset we last wrote.
			if (f['falco.sha256_rules_file.rules_yaml'] === this.wantSha && this.readyWaiters.length) {
				const w = this.readyWaiters;
				this.readyWaiters = [];
				for (const fn of w) {
					fn();
				}
			}
			const drops = ['scap.n_drops', 'scap.n_drops_buffer_total', 'falco.outputs_queue_num_drops'].map(k => f[k]).find(v => typeof v === 'number' && v > 0) as number | undefined;
			for (const w of this.tabs.values()) {
				this.d.hub.heartbeat(w.tabId);
				if (drops) {
					this.d.hub.setObservation(w.tabId, 'degraded', `Falco dropped ${drops} kernel events`, { sensor: 'falco' });
				}
			}
			return;
		}
		const cid = f['container.id'];
		const w = typeof cid === 'string' ? this.tabs.get(cid) : undefined;
		if (!w || typeof e.rule !== 'string') {
			return;
		}
		const draft = falcoToDraft(e.rule, f);
		if (draft) {
			this.d.hub.emit(w.tabId, { ...draft, ...SOURCE, ...(typeof e.time === 'string' ? { sensorTime: e.time.replace(/(\.\d{3})\d*Z$/, '$1Z') } : {}) });
		}
	}
}

const s = (v: unknown, max = 1024) => (typeof v === 'string' && v !== '<NA>' ? v.slice(0, max) : undefined);
const n = (v: unknown) => (typeof v === 'number' && Number.isInteger(v) && v >= 0 ? v : typeof v === 'string' && /^\d{1,10}$/.test(v) ? Number(v) : undefined);
function arg(args: string | undefined, key: string): string | undefined {
	return args ? new RegExp(`(?:^| )${key}=(\\S+)`).exec(args)?.[1] : undefined;
}
function result(args: string | undefined): string {
	const res = arg(args, 'res') ?? '';
	if (res === '0') {
		return 'ok';
	}
	const m = /\(([A-Z0-9]+)\)/.exec(res);
	return m ? (m[1] === 'EINPROGRESS' ? 'pending' : m[1]) : res || '?';
}

/** Map one Falco event (our capture rules only) to an event draft. */
export function falcoToDraft(rule: string, f: Record<string, unknown>): Record<string, unknown> | undefined {
	const exe = s(f['proc.exepath'], 512);
	const pid = n(f['proc.pid']), ppid = n(f['proc.ppid']);
	const lineage: Array<{ pid: number; exe: string }> = [];
	const pc = s(f['proc.pcmdline'], 256);
	if (ppid !== undefined && pc) {
		lineage.push({ pid: ppid, exe: pc });
	}
	for (const i of [2, 3]) {
		const ap = n(f[`proc.apid[${i}]`]), an = s(f[`proc.aname[${i}]`], 128);
		if (ap !== undefined && an) {
			lineage.push({ pid: ap, exe: an });
		}
	}
	const base = exe ? exe.slice(exe.lastIndexOf('/') + 1) : '?';
	const proc = { pid, ppid, uid: n(f['user.uid']), exe, lineage };
	const args = s(f['evt.args'], 2048);
	switch (rule) {
		case 'seclab.exec': {
			const name = s(f['proc.name'], 256) ?? base;
			const rest = s(f['proc.args'], 4096) ?? '';
			// Falco joins argv with spaces; boundaries are lost (marked argvJoined).
			const argv = [name, ...(rest ? rest.split(' ') : [])];
			return { class: 'process.exec', priority: 'informational', proc: { ...proc, argv }, summary: `exec ${summarizeArgv(argv, 200)}`, detail: { argvJoined: true } };
		}
		case 'seclab.connect': {
			const t = s(f['fd.typechar'], 2);
			const addr = arg(args, 'addr') ?? '?';
			const family = t === '4' ? 'inet' : t === '6' ? 'inet6' : t === 'u' ? 'unix' : 'other';
			let host = addr, port: number | undefined;
			const m = /^(.*):(\d{1,5})$/.exec(addr);
			if (family !== 'unix' && m) {
				host = m[1].replace(/^\[|\]$/g, '');
				port = Number(m[2]);
			}
			const res = result(args);
			const l4 = s(f['fd.l4proto'], 8);
			const proto = family === 'unix' ? undefined : l4 === 'tcp' ? 'tcp' : l4 === 'udp' ? 'udp' : undefined;
			// The tab-side source port (for the exact join to the broker's clientPort): Falco's
			// fd.cport (the client end; fd.lport is the server's), else the client side of the tuple.
			const lp = Number(f['fd.cport']);
			const tupleCport = /tuple=[^ ]*?:(\d{1,5})->/.exec(args ?? '')?.[1];
			const localPort = family === 'unix' ? undefined : Number.isInteger(lp) && lp > 0 && lp <= 65535 ? lp : tupleCport && Number(tupleCport) > 0 && Number(tupleCport) <= 65535 ? Number(tupleCport) : undefined;
			return { class: 'net.connect', priority: family === 'unix' ? 'debug' : 'informational', proc, net: { addr: host, port, family, result: res, ...(proto ? { proto } : {}), ...(localPort ? { localPort } : {}) }, summary: `connect ${family === 'unix' ? host : `${host}:${port ?? '?'}`} ${res} by ${base}` };
		}
		case 'seclab.open': {
			const p = s(f['fd.name']) ?? '?';
			const flags = s(f['evt.arg.flags'], 128) ?? '';
			const write = /O_WRONLY|O_RDWR|O_CREAT|O_TRUNC/.test(flags);
			return { class: write ? 'file.write' : 'file.open', priority: 'warning', proc, file: { path: p, op: write ? 'write' : 'read' }, detail: { flags }, summary: `${write ? 'write' : 'open'} ${p} by ${base}` };
		}
		case 'seclab.fileop': {
			const type = s(f['evt.type'], 32) ?? '';
			if (/^unlink/.test(type)) {
				const p = s(f['fs.path.name']) ?? '?';
				return { class: 'file.delete', priority: 'informational', proc, file: { path: p, op: 'delete' }, summary: `delete ${p}` };
			}
			if (/chmod/.test(type)) {
				const p = s(f['fs.path.name']) ?? '?';
				const mode = arg(args, 'mode') ?? '';
				const exec = /^(?:0?[0-7]*[1357][0-7]{0,2})/.test(mode.replace(/\(.*$/, '')) && (parseInt(mode, 8) & 0o111) !== 0;
				return { class: 'file.chmod', priority: exec ? 'notice' : 'debug', proc, file: { path: p, op: 'chmod' }, detail: { mode: mode.slice(0, 32), executable: exec }, summary: `chmod ${mode} ${p}` };
			}
			const to = s(f['fs.path.target']) ?? '?', from = s(f['fs.path.source']) ?? '?';
			const op = type.startsWith('rename') ? 'rename' : type.startsWith('sym') ? 'symlink' : 'link';
			return { class: 'file.rename', priority: 'informational', proc, file: { path: to, op }, detail: { from }, summary: `${op} ${from} -> ${to}` };
		}
		case 'seclab.priv': {
			const type = s(f['evt.type'], 32) ?? '?';
			const res = result(args);
			if (/^(set|cap)/.test(type)) {
				const toRoot = /(?:^| )(?:uid|ruid|euid|suid|gid)=0\b/.test(args ?? '');
				return { class: 'priv.change', priority: toRoot && res === 'ok' ? 'critical' : 'notice', proc, detail: { call: type, args: (args ?? '').slice(0, 128), result: res }, summary: `${type} ${res}` };
			}
			if (type === 'ptrace') {
				return { class: 'proc.ptrace', priority: 'warning', proc, detail: { call: type, args: (args ?? '').slice(0, 128), result: res }, summary: `ptrace ${(args ?? '').slice(0, 80)} (${res})` };
			}
			if (/kill$/.test(type)) {
				const target = Number(arg(args, 'pid') ?? arg(args, 'tid'));
				if (target === pid) {
					return undefined;
				}
				return { class: 'proc.signal', priority: target === 1 ? 'warning' : 'debug', proc, detail: { call: type, target: Number.isInteger(target) ? target : -1, result: res, tamper: false }, summary: `${type} to ${target} (${res})` };
			}
			return { class: 'proc.sensitive', priority: 'warning', proc, detail: { call: type, args: (args ?? '').slice(0, 128), result: res }, summary: `${type} (${res})` };
		}
		default:
			return undefined;
	}
}
